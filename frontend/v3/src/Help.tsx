export function explanation(term: string): string | undefined {
  if (explanations[term]) return explanations[term];
  if (/ID$|^原机尾$|^原机组$/.test(term)) return "用于引用和关联这条业务记录的标识符；必须与相关数据中的引用保持一致，普通编辑中默认只读。";
  if (/起飞|到达|开始时间|结束时间/.test(term)) return "对应记录的时间或延误字段，请结合字段单位读取。AIR 使用 UTC，厦航使用北京时间；修改后需要保存并校验时间边界。";
  if (/成本/.test(term)) return "目标函数使用的成本或系数，单位按所选研究目标解释；当前值以保存的输入和运行审计为准。";
  if (/人数|旅客数|需求/.test(term)) return "该记录对应的旅客数量，单位为人；参与人数守恒及容量检查。";
  return undefined;
}

export function Help({ term, text }: { term: string; text?: string }) {
  const content = text ?? explanation(term);
  const id = useId();
  const trigger = useRef<HTMLButtonElement>(null);
  const closeTimer = useRef<ReturnType<typeof setTimeout> | undefined>(undefined);
  const [position, setPosition] = useState<{ left: number; top: number; above: boolean } | null>(null);
  useEffect(() => () => clearTimeout(closeTimer.current), []);
  useEffect(() => {
    if (!position) return;
    const closeOther = (event: Event) => { if ((event as CustomEvent).detail !== id) setPosition(null); };
    const outside = (event: Event) => { if (!trigger.current?.contains(event.target as Node) && !document.getElementById(id)?.contains(event.target as Node)) setPosition(null); };
    const escape = (event: KeyboardEvent) => { if (event.key === "Escape") setPosition(null); };
    const resize = () => setPosition(null);
    window.addEventListener("wb3-help-open", closeOther);
    window.addEventListener("pointerdown", outside);
    window.addEventListener("keydown", escape);
    window.addEventListener("resize", resize);
    return () => { window.removeEventListener("wb3-help-open", closeOther); window.removeEventListener("pointerdown", outside); window.removeEventListener("keydown", escape); window.removeEventListener("resize", resize); };
  }, [id, position]);
  if (!content) return null;
  const keep = () => clearTimeout(closeTimer.current);
  const hide = () => { clearTimeout(closeTimer.current); closeTimer.current = setTimeout(() => setPosition(null), 150); };
  const show = () => {
    keep();
    const rect = trigger.current?.getBoundingClientRect();
    if (!rect) return;
    window.dispatchEvent(new CustomEvent("wb3-help-open", { detail: id }));
    setPosition({ left: Math.max(12, Math.min(rect.left, window.innerWidth - Math.min(440, window.innerWidth - 24) - 12)), top: rect.bottom + 8, above: rect.bottom > window.innerHeight * .65 });
  };
  return <span className="help-anchor" onMouseEnter={show} onMouseLeave={hide}>
    <button ref={trigger} type="button" className="help-trigger" aria-label={`解释：${term}`} aria-describedby={position ? id : undefined} aria-expanded={!!position} onFocus={show} onBlur={() => setPosition(null)} onClick={event => { event.preventDefault(); event.stopPropagation(); show(); }} onKeyDown={event => { if (event.key === "Escape") { event.preventDefault(); event.stopPropagation(); setPosition(null); } }}><CircleHelp size={15} aria-hidden="true"/></button>
    {position && createPortal(<span id={id} role="tooltip" className="help-tooltip" onMouseEnter={keep} onMouseLeave={hide} style={{ left: position.left, top: position.above ? undefined : position.top, bottom: position.above ? Math.max(12, window.innerHeight - position.top + 40) : undefined }}><strong>{term}</strong><span>{content}</span></span>, trigger.current?.closest("dialog") ?? document.body)}
  </span>;
}

export function Term({ children, text }: { children: string; text?: string }) {
  return <span className="help-term"><span>{children}</span><Help term={children} text={text}/></span>;
}
